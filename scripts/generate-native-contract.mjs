import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const contract = JSON.parse(await readFile(new URL('contracts/native-api.json', root), 'utf8'));

const generatedNotice = 'Generated by scripts/generate-native-contract.mjs. Do not edit.';
const outputs = new Map([
  ['src/generated/native-contract.ts', renderTypeScript()],
  ['ios/Sources/CapacitorOidcPlugin/NativeContract.generated.swift', renderSwift()],
  ['android/src/main/java/com/jojopirker/capacitor/oidc/NativeContract.java', renderJava()],
]);

if (process.argv.includes('--check')) {
  const stale = [];
  for (const [path, expected] of outputs) {
    const actual = await readFile(new URL(path, root), 'utf8');
    if (actual !== expected) stale.push(path);
  }
  if (stale.length > 0) {
    throw new Error(`Generated native contract is stale: ${stale.join(', ')}`);
  }
} else {
  await Promise.all([...outputs].map(([path, contents]) => writeFile(new URL(path, root), contents)));
}

function renderTypeScript() {
  return `// ${generatedNotice}

export const nativeContract = {
  pluginName: '${contract.pluginName}',
${renderTypeScriptGroup('methods', contract.methods)}
${renderTypeScriptGroup('fields', contract.fields)}
${renderTypeScriptGroup('errorCodes', contract.errorCodes)}
${renderTypeScriptGroup('keychainAccessibility', contract.keychainAccessibility)}
} as const;

export type NativeErrorCode = (typeof nativeContract.errorCodes)[keyof typeof nativeContract.errorCodes];
`;
}

function renderTypeScriptGroup(name, values) {
  const entries = Object.entries(values).map(([key, value]) => `    ${key}: '${value}',`);
  return `  ${name}: {\n${entries.join('\n')}\n  },`;
}

function renderSwift() {
  return `// ${generatedNotice}

enum NativeContract {
    static let pluginName = "${contract.pluginName}"

${renderSwiftGroup('Method', contract.methods)}
${renderSwiftGroup('Field', contract.fields)}
${renderSwiftGroup('ErrorCode', contract.errorCodes)}
${renderSwiftGroup('KeychainAccessibility', contract.keychainAccessibility)}
}
`;
}

function renderSwiftGroup(name, values) {
  const entries = Object.entries(values).map(([key, value]) => `        static let ${key} = "${value}"`);
  return `    enum ${name} {\n${entries.join('\n')}\n    }`;
}

function renderJava() {
  return `// ${generatedNotice}
package com.jojopirker.capacitor.oidc;

final class NativeContract {

    static final String PLUGIN_NAME = "${contract.pluginName}";

${renderJavaGroup('METHOD', contract.methods)}
${renderJavaGroup('FIELD', contract.fields)}
${renderJavaGroup('ERROR', contract.errorCodes)}
${renderJavaGroup('KEYCHAIN_ACCESSIBILITY', contract.keychainAccessibility)}

    private NativeContract() {}
}
`;
}

function renderJavaGroup(prefix, values) {
  return Object.entries(values)
    .map(([key, value]) => `    static final String ${prefix}_${toUpperSnake(key)} = "${value}";`)
    .join('\n');
}

function toUpperSnake(value) {
  return value.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
}
